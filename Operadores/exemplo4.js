const primeiroNome = "Ana";
const sobrenome = "Silva";
const idade = 25
// Concatenação tradicional usando o operador +
const nomeCompleto = primeiroNome + " " + sobrenome;
console.log("Usuário cadastrado: " + nomeCompleto);
// Saída: Usuário cadastrado: Ana Silva
console.log(nomeCompleto + " tem " + idade + " anos." );
// Saída: Ana Silva tem 25 anos